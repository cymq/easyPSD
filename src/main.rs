/// Processes queued preview jobs from `pending_preview_job` and updates the Slint window.
fn run_preview_worker_loop(state_clone: Arc<Mutex<AppInner>>, ui_weak: slint::Weak<AppWindow>) {
    loop {
        let (job, source, icc) = {
            let mut s = state_clone.lock().unwrap();
            let Some(job) = s.pending_preview_job.take() else {
                s.preview_worker_busy = false;
                break;
            };
            if s.conversion_generation != job.generation || !s.cmyk_enabled {
                continue;
            }
            let (Some(src), Some(icc)) = (s.cached_image.clone(), s.cached_icc.clone()) else {
                s.preview_worker_busy = false;
                break;
            };
            (job, src, icc)
        };

        let intents_slice: &[RenderingIntent] = if job.all_intents {
            &RenderingIntent::ALL
        } else {
            std::slice::from_ref(&job.active_intent)
        };

        if let Ok(rendered) = crate::conversion::render_intent_previews(
            &source,
            &icc,
            job.adjustments,
            job.black_point_compensation,
            intents_slice,
        ) {
            let rendered_buffers: Vec<(RenderingIntent, SharedPixelBuffer<Rgba8Pixel>)> = rendered
                .iter()
                .map(|(intent, preview)| (*intent, raw_preview_to_buffer(preview)))
                .collect();

            let should_update_ui = {
                let mut s = state_clone.lock().unwrap();
                if s.conversion_generation == job.generation && s.cmyk_enabled {
                    let matches_latest = s.adjustments == job.adjustments
                        && s.black_point_compensation == job.black_point_compensation;
                    for (intent, buf) in rendered_buffers {
                        let idx = intent.to_index();
                        s.preview_buffers[idx] = Some(buf);
                        if matches_latest {
                            s.intent_stale[idx] = false;
                        }
                    }
                    true
                } else {
                    false
                }
            };

            if should_update_ui {
                let state_for_ui = Arc::clone(&state_clone);
                let _ = ui_weak.upgrade_in_event_loop(move |ui| {
                    let s = state_for_ui.lock().unwrap();
                    sync_previews_to_window(&ui, &s);
                });
            }
        }
    }
}

/// Spawns the single-flight background worker if not already running to process `pending_preview_job`.
fn ensure_preview_worker_running(state: &Arc<Mutex<AppInner>>, ui_weak: slint::Weak<AppWindow>) {
    {
        let mut inner = state.lock().unwrap();
        if inner.preview_worker_busy || inner.pending_preview_job.is_none() {
            return;
        }
        inner.preview_worker_busy = true;
    }

    let state_clone = Arc::clone(state);

    #[cfg(not(target_arch = "wasm32"))]
    std::thread::spawn(move || {
        run_preview_worker_loop(state_clone, ui_weak);
    });

    #[cfg(target_arch = "wasm32")]
    wasm_bindgen_futures::spawn_local(async move {
        let _ = wasm_bindgen_futures::JsFuture::from(js_sys::Promise::resolve(
            &wasm_bindgen::JsValue::NULL,
        ))
        .await;
        run_preview_worker_loop(state_clone, ui_weak);
    });
}

/// Schedules an interactive adjustment or Black Point Compensation preview update.
fn schedule_adjustment_preview(
    state: &Arc<Mutex<AppInner>>,
    ui_weak: slint::Weak<AppWindow>,
    adjustments: AdjustmentParams,
    black_point_compensation: bool,
    all_intents: bool,
) {
    let should_spawn = {
        let mut inner = state.lock().unwrap();
        let params_changed = inner.adjustments != adjustments
            || inner.black_point_compensation != black_point_compensation;
        inner.adjustments = adjustments;
        inner.black_point_compensation = black_point_compensation;

        if params_changed {
            for i in 1..5 {
                inner.intent_stale[i] = true;
            }
        }

        if inner.cmyk_enabled && inner.cached_image.is_some() && inner.cached_icc.is_some() {
            let active_intent = RenderingIntent::from_index(inner.active_index)
                .unwrap_or(RenderingIntent::Perceptual);
            inner.pending_preview_job = Some(PreviewJob {
                generation: inner.conversion_generation,
                adjustments,
                black_point_compensation,
                all_intents,
                active_intent,
            });
            true
        } else {
            false
        }
    };

    if should_spawn {
        ensure_preview_worker_running(state, ui_weak);
    }
}

/// Executes initial loading and 4-intent preview rendering for the active generation.
fn run_initial_preview_load(
    state_clone: Arc<Mutex<AppInner>>,
    ui_weak: slint::Weak<AppWindow>,
    input_path: String,
    icc_path: String,
    existing_img: Option<CachedImage>,
    existing_icc: Option<CachedIcc>,
    current_gen: u64,
    current_adjustments: AdjustmentParams,
    current_bpc: bool,
) {
    let load_result = (|| -> Result<
        (CachedImage, CachedIcc, Vec<(RenderingIntent, RawPreview)>),
        crate::conversion::AppError,
    > {
        let src = match existing_img {
            Some(c) => c,
            None => crate::conversion::load_preview_source(&input_path)?,
        };
        let icc = match existing_icc {
            Some(c) => c,
            None => crate::conversion::load_cmyk_icc(&icc_path)?,
        };

        let rendered = crate::conversion::render_intent_previews(
            &src,
            &icc,
            current_adjustments,
            current_bpc,
            &RenderingIntent::ALL,
        )?;

        Ok((src, icc, rendered))
    })();

    match load_result {
        Ok((src, icc, rendered)) => {
            let orig_buf = SharedPixelBuffer::<Rgba8Pixel>::clone_from_slice(
                &src.rgba,
                src.width as u32,
                src.height as u32,
            );
            let rendered_buffers: Vec<(RenderingIntent, SharedPixelBuffer<Rgba8Pixel>)> = rendered
                .iter()
                .map(|(intent, preview)| (*intent, raw_preview_to_buffer(preview)))
                .collect();

            let should_update_ui = {
                let mut s = state_clone.lock().unwrap();
                if s.conversion_generation == current_gen && s.cmyk_enabled {
                    s.cached_image = Some(src);
                    s.cached_icc = Some(icc);
                    s.preview_buffers[0] = Some(orig_buf);
                    for (intent, buf) in rendered_buffers {
                        let idx = intent.to_index();
                        s.preview_buffers[idx] = Some(buf);
                        s.intent_stale[idx] = false;
                    }
                    s.loading = false;
                    true
                } else {
                    false
                }
            };

            if should_update_ui {
                let state_for_ui = Arc::clone(&state_clone);
                let _ = ui_weak.upgrade_in_event_loop(move |ui| {
                    let s = state_for_ui.lock().unwrap();
                    ui.set_loading(s.loading);
                    sync_previews_to_window(&ui, &s);
                });
            }
        }
        Err(_) => {
            let should_update_ui = {
                let mut s = state_clone.lock().unwrap();
                if s.conversion_generation == current_gen {
                    s.loading = false;
                    true
                } else {
                    false
                }
            };
            if should_update_ui {
                let state_for_ui = Arc::clone(&state_clone);
                let _ = ui_weak.upgrade_in_event_loop(move |ui| {
                    let s = state_for_ui.lock().unwrap();
                    ui.set_loading(s.loading);
                    sync_previews_to_window(&ui, &s);
                });
            }
        }
    }
}

/// Handles changes to the source image path, target ICC path, or CMYK mode toggle.
fn handle_settings_changed(state: &Arc<Mutex<AppInner>>, window: &AppWindow) {
    let (
        input_path,
        icc_path,
        cmyk_enabled,
        existing_img,
        existing_icc,
        current_gen,
        current_adjustments,
        current_bpc,
    ) = {
        let mut inner = state.lock().unwrap();
        inner.pending_preview_job = None;

        if inner
            .cached_image
            .as_ref()
            .is_some_and(|c| c.path != inner.input_path)
        {
            inner.cached_image = None;
        }
        if inner
            .cached_icc
            .as_ref()
            .is_some_and(|c| c.path != inner.icc_path)
        {
            inner.cached_icc = None;
        }

        for buf in &mut inner.preview_buffers {
            *buf = None;
        }
        inner.intent_stale = [false; 5];
        inner.conversion_generation += 1;
        // Clear any loading flag from an invalidated previous generation so UI never deadlocks
        inner.loading = false;

        (
            inner.input_path.clone(),
            inner.icc_path.clone(),
            inner.cmyk_enabled,
            inner.cached_image.clone(),
            inner.cached_icc.clone(),
            inner.conversion_generation,
            inner.adjustments,
            inner.black_point_compensation,
        )
    };

    window.set_loading(false);
    window.set_input_display(display_filename(&input_path, INPUT_PLACEHOLDER).into());
    window.set_has_input(!input_path.is_empty());
    window.set_icc_display(display_filename(&icc_path, ICC_PLACEHOLDER).into());
    window.set_has_icc(!icc_path.is_empty());
    window.set_has_preview(false);
    window.set_original_preview(Image::default());
    window.set_active_preview(Image::default());

    #[cfg(not(target_arch = "wasm32"))]
    let can_render = cmyk_enabled
        && !input_path.is_empty()
        && !icc_path.is_empty()
        && Path::new(&input_path).exists()
        && Path::new(&icc_path).exists();

    #[cfg(target_arch = "wasm32")]
    let can_render = cmyk_enabled && existing_img.is_some() && existing_icc.is_some();

    if can_render {
        {
            let mut inner = state.lock().unwrap();
            inner.loading = true;
            window.set_loading(true);
        }

        let state_clone = Arc::clone(state);
        let ui_weak = window.as_weak();

        #[cfg(not(target_arch = "wasm32"))]
        std::thread::spawn(move || {
            run_initial_preview_load(
                state_clone,
                ui_weak,
                input_path,
                icc_path,
                existing_img,
                existing_icc,
                current_gen,
                current_adjustments,
                current_bpc,
            );
        });

        #[cfg(target_arch = "wasm32")]
        wasm_bindgen_futures::spawn_local(async move {
            let _ = wasm_bindgen_futures::JsFuture::from(js_sys::Promise::resolve(
                &wasm_bindgen::JsValue::NULL,
            ))
            .await;
            run_initial_preview_load(
                state_clone,
                ui_weak,
                input_path,
                icc_path,
                existing_img,
                existing_icc,
                current_gen,
                current_adjustments,
                current_bpc,
            );
        });
    }
}

fn main() -> Result<(), slint::PlatformError> {
    let app = AppWindow::new()?;
    app.set_app_version(env!("CARGO_PKG_VERSION").into());

    #[cfg(target_arch = "wasm32")]
    setup_browser_viewport_sync(&app);

    let state = Arc::new(Mutex::new(AppInner::new()));

    // 0. Open GitHub Repository & Parse Direct Numeric Input in Adjustment Boxes
    app.on_open_github(|| {
        open_url(GITHUB_REPO_URL);
    });
    app.on_parse_adjustment_input(|raw, current, min_val, max_val| {
        parse_adjustment_input(raw.as_str(), current, min_val, max_val)
    });

    // 1. Toggle CMYK Mode
    {
        let state = Arc::clone(&state);
        let ui_weak = app.as_weak();
        app.on_toggle_cmyk(move |enabled| {
            let Some(ui) = ui_weak.upgrade() else { return };
            {
                let mut inner = state.lock().unwrap();
                inner.cmyk_enabled = enabled;
            }
            handle_settings_changed(&state, &ui);
        });
    }

    // 2. Select Input Image File
    {
        let state = Arc::clone(&state);
        let ui_weak = app.as_weak();
        app.on_select_input_file(move || {
            let Some(ui) = ui_weak.upgrade() else { return };
            if state.lock().unwrap().loading {
                return;
            }

            #[cfg(not(target_arch = "wasm32"))]
            if let Some(path) = rfd::FileDialog::new()
                .set_title("元の画像を選択")
                .add_filter(
                    "画像ファイル",
                    &["png", "jpg", "jpeg", "tiff", "tif", "webp"],
                )
                .pick_file()
            {
                {
                    let mut inner = state.lock().unwrap();
                    inner.input_path = path.to_string_lossy().to_string();
                }
                handle_settings_changed(&state, &ui);
            }

            #[cfg(target_arch = "wasm32")]
            {
                let state_for_pick = Arc::clone(&state);
                let ui_weak_for_pick = ui.as_weak();
                pick_file_in_browser(
                    ".png,.jpg,.jpeg,.tiff,.tif,.webp,image/*",
                    move |name, bytes| {
                        let Some(ui) = ui_weak_for_pick.upgrade() else {
                            return;
                        };
                        if let Ok(cached_img) =
                            crate::conversion::load_preview_source_from_memory(&name, &bytes)
                        {
                            {
                                let mut inner = state_for_pick.lock().unwrap();
                                inner.input_path = name;
                                inner.input_bytes = Some(Arc::new(bytes));
                                inner.cached_image = Some(cached_img);
                            }
                            handle_settings_changed(&state_for_pick, &ui);
                        }
                    },
                );
            }
        });
    }

    // 3. Select Target CMYK ICC Profile
    {
        let state = Arc::clone(&state);
        let ui_weak = app.as_weak();
        app.on_select_icc_file(move || {
            let Some(ui) = ui_weak.upgrade() else { return };
            if state.lock().unwrap().loading {
                return;
            }

            #[cfg(not(target_arch = "wasm32"))]
            if let Some(path) = rfd::FileDialog::new()
                .set_title("CMYKカラープロファイルを選択")
                .add_filter("CMYKカラープロファイル", &["icc", "icm"])
                .pick_file()
            {
                {
                    let mut inner = state.lock().unwrap();
                    inner.icc_path = path.to_string_lossy().to_string();
                }
                handle_settings_changed(&state, &ui);
            }

            #[cfg(target_arch = "wasm32")]
            {
                let state_for_pick = Arc::clone(&state);
                let ui_weak_for_pick = ui.as_weak();
                pick_file_in_browser(".icc,.icm", move |name, bytes| {
                    let Some(ui) = ui_weak_for_pick.upgrade() else {
                        return;
                    };
                    if let Ok(cached_icc) =
                        crate::conversion::load_cmyk_icc_from_bytes(&name, bytes)
                    {
                        {
                            let mut inner = state_for_pick.lock().unwrap();
                            inner.icc_path = name;
                            inner.cached_icc = Some(cached_icc);
                        }
                        handle_settings_changed(&state_for_pick, &ui);
                    }
                });
            }
        });
    }

    // 4. Toggle Black Point Compensation (BPC)
    {
        let state = Arc::clone(&state);
        let ui_weak = app.as_weak();
        app.on_toggle_bpc(move |bpc_enabled| {
            let Some(ui) = ui_weak.upgrade() else { return };
            let adjustments = read_adjustments_from_window(&ui);
            schedule_adjustment_preview(&state, ui.as_weak(), adjustments, bpc_enabled, true);
        });
    }

    // 5. Select Rendering Intent
    {
        let state = Arc::clone(&state);
        let ui_weak = app.as_weak();
        app.on_select_intent(move |index| {
            let Some(ui) = ui_weak.upgrade() else { return };
            let active_index = (index as usize).clamp(1, 4);
            let needs_worker = {
                let mut inner = state.lock().unwrap();
                inner.active_index = active_index;
                sync_previews_to_window(&ui, &inner);

                if inner.intent_stale[active_index]
                    && inner.cached_image.is_some()
                    && inner.cached_icc.is_some()
                {
                    let active_intent = RenderingIntent::from_index(active_index)
                        .unwrap_or(RenderingIntent::Perceptual);
                    inner.pending_preview_job = Some(PreviewJob {
                        generation: inner.conversion_generation,
                        adjustments: inner.adjustments,
                        black_point_compensation: inner.black_point_compensation,
                        all_intents: true,
                        active_intent,
                    });
                    true
                } else {
                    false
                }
            };

            if needs_worker {
                ensure_preview_worker_running(&state, ui.as_weak());
            }
        });
    }

    // 6. Image Adjustment Dragging (computes only active intent for smooth real-time preview)
    {
        let state = Arc::clone(&state);
        let ui_weak = app.as_weak();
        app.on_adjustment_dragging(move || {
            let Some(ui) = ui_weak.upgrade() else { return };
            let adjustments = read_adjustments_from_window(&ui);
            let bpc = ui.get_black_point_compensation();
            schedule_adjustment_preview(&state, ui.as_weak(), adjustments, bpc, false);
        });
    }

    // 7. Image Adjustment Committed / Released (recomputes all 4 intents)
    {
        let state = Arc::clone(&state);
        let ui_weak = app.as_weak();
        app.on_adjustment_committed(move || {
            let Some(ui) = ui_weak.upgrade() else { return };
            let adjustments = read_adjustments_from_window(&ui);
            let bpc = ui.get_black_point_compensation();
            schedule_adjustment_preview(&state, ui.as_weak(), adjustments, bpc, true);
        });
    }

    // 8. Reset All Image Adjustments
    {
        let state = Arc::clone(&state);
        let ui_weak = app.as_weak();
        app.on_reset_adjustments(move || {
            let Some(ui) = ui_weak.upgrade() else { return };
            let mut adjustments = state.lock().unwrap().adjustments;
            if !adjustments.is_identity() {
                adjustments.reset();
            }
            let bpc = ui.get_black_point_compensation();
            schedule_adjustment_preview(&state, ui.as_weak(), adjustments, bpc, true);
        });
    }

    // 9. Export PSD File
    {
        let state = Arc::clone(&state);
        let ui_weak = app.as_weak();
        app.on_export_psd(move || {
            let Some(ui) = ui_weak.upgrade() else { return };

            #[cfg(not(target_arch = "wasm32"))]
            {
                let (
                    input_path,
                    icc_path,
                    cmyk_enabled,
                    loading,
                    active_index,
                    export_bpc,
                    export_adjustments,
                ) = {
                    let inner = state.lock().unwrap();
                    (
                        inner.input_path.clone(),
                        inner.icc_path.clone(),
                        inner.cmyk_enabled,
                        inner.loading,
                        inner.active_index,
                        inner.black_point_compensation,
                        inner.adjustments,
                    )
                };

                if loading || !Path::new(&input_path).exists() {
                    return;
                }

                if cmyk_enabled && !Path::new(&icc_path).exists() {
                    return;
                }

                if !cmyk_enabled {
                    let orig_name = Path::new(&input_path)
                        .file_stem()
                        .map(|s| s.to_string_lossy().to_string())
                        .unwrap_or_else(|| "output".to_string());
                    let default_name = format!("{}_flat.psd", orig_name);

                    if let Some(save_path) = rfd::FileDialog::new()
                        .set_title("PSDの保存先を選択")
                        .set_file_name(&default_name)
                        .add_filter("PSDファイル (*.psd)", &["psd"])
                        .save_file()
                    {
                        let save_path_str = save_path.to_string_lossy().to_string();
                        {
                            let mut inner = state.lock().unwrap();
                            inner.loading = true;
                            ui.set_loading(true);
                        }

                        let state_clone = Arc::clone(&state);
                        let ui_weak_thread = ui.as_weak();

                        std::thread::spawn(move || {
                            let result =
                                crate::psd::export_rgb_psd_file(&input_path, &save_path_str);
                            {
                                let mut s = state_clone.lock().unwrap();
                                s.loading = false;
                                if result.is_ok() {
                                    open_folder(&save_path_str);
                                }
                            }

                            let state_for_ui = Arc::clone(&state_clone);
                            let _ = ui_weak_thread.upgrade_in_event_loop(move |ui| {
                                let s = state_for_ui.lock().unwrap();
                                ui.set_loading(s.loading);
                            });
                        });
                    }
                } else if active_index != 0 {
                    let orig_name = Path::new(&input_path)
                        .file_stem()
                        .map(|s| s.to_string_lossy().to_string())
                        .unwrap_or_else(|| "output".to_string());
                    let suffix = RenderingIntent::from_index(active_index)
                        .map(|intent| intent.suffix())
                        .unwrap_or("converted");
                    let default_name = format!("{}_cmyk_{}.psd", orig_name, suffix);

                    if let Some(save_path) = rfd::FileDialog::new()
                        .set_title("PSDの保存先を選択")
                        .set_file_name(&default_name)
                        .add_filter("PSDファイル (*.psd)", &["psd"])
                        .save_file()
                    {
                        let save_path_str = save_path.to_string_lossy().to_string();
                        let intent = RenderingIntent::from_index(active_index)
                            .unwrap_or(RenderingIntent::Perceptual);

                        {
                            let mut inner = state.lock().unwrap();
                            inner.loading = true;
                            ui.set_loading(true);
                        }

                        let state_clone = Arc::clone(&state);
                        let ui_weak_thread = ui.as_weak();

                        std::thread::spawn(move || {
                            let result = crate::psd::export_cmyk_psd_file(
                                &input_path,
                                &icc_path,
                                intent,
                                export_bpc,
                                export_adjustments,
                                &save_path_str,
                            );
                            {
                                let mut s = state_clone.lock().unwrap();
                                s.loading = false;
                                if result.is_ok() {
                                    open_folder(&save_path_str);
                                }
                            }

                            let state_for_ui = Arc::clone(&state_clone);
                            let _ = ui_weak_thread.upgrade_in_event_loop(move |ui| {
                                let s = state_for_ui.lock().unwrap();
                                ui.set_loading(s.loading);
                            });
                        });
                    }
                }
            }

            #[cfg(target_arch = "wasm32")]
            {
                let (
                    input_path,
                    input_bytes,
                    cached_icc,
                    cmyk_enabled,
                    loading,
                    active_index,
                    export_bpc,
                    export_adjustments,
                ) = {
                    let inner = state.lock().unwrap();
                    (
                        inner.input_path.clone(),
                        inner.input_bytes.clone(),
                        inner.cached_icc.clone(),
                        inner.cmyk_enabled,
                        inner.loading,
                        inner.active_index,
                        inner.black_point_compensation,
                        inner.adjustments,
                    )
                };

                let Some(input_bytes) = input_bytes else {
                    return;
                };
                if loading {
                    return;
                }

                let orig_name = Path::new(&input_path)
                    .file_stem()
                    .map(|s| s.to_string_lossy().to_string())
                    .unwrap_or_else(|| "output".to_string());

                if !cmyk_enabled {
                    let default_name = format!("{}_flat.psd", orig_name);
                    {
                        let mut inner = state.lock().unwrap();
                        inner.loading = true;
                        ui.set_loading(true);
                    }
                    let state_clone = Arc::clone(&state);
                    let ui_weak_task = ui.as_weak();

                    wasm_bindgen_futures::spawn_local(async move {
                        let _ = wasm_bindgen_futures::JsFuture::from(js_sys::Promise::resolve(
                            &wasm_bindgen::JsValue::NULL,
                        ))
                        .await;
                        if let Ok(psd_bytes) = crate::psd::export_rgb_psd_bytes(&input_bytes) {
                            download_bytes_in_browser(&default_name, &psd_bytes);
                        }
                        {
                            let mut s = state_clone.lock().unwrap();
                            s.loading = false;
                        }
                        if let Some(ui) = ui_weak_task.upgrade() {
                            ui.set_loading(false);
                        }
                    });
                } else if active_index != 0 {
                    let Some(icc) = cached_icc else {
                        return;
                    };
                    let intent = RenderingIntent::from_index(active_index)
                        .unwrap_or(RenderingIntent::Perceptual);
                    let suffix = intent.suffix();
                    let default_name = format!("{}_cmyk_{}.psd", orig_name, suffix);

                    {
                        let mut inner = state.lock().unwrap();
                        inner.loading = true;
                        ui.set_loading(true);
                    }
                    let state_clone = Arc::clone(&state);
                    let ui_weak_task = ui.as_weak();

                    wasm_bindgen_futures::spawn_local(async move {
                        let _ = wasm_bindgen_futures::JsFuture::from(js_sys::Promise::resolve(
                            &wasm_bindgen::JsValue::NULL,
                        ))
                        .await;
                        if let Ok(psd_bytes) = crate::psd::export_cmyk_psd_bytes(
                            &input_bytes,
                            &icc,
                            intent,
                            export_bpc,
                            export_adjustments,
                        ) {
                            download_bytes_in_browser(&default_name, &psd_bytes);
                        }
                        {
                            let mut s = state_clone.lock().unwrap();
                            s.loading = false;
                        }
                        if let Some(ui) = ui_weak_task.upgrade() {
                            ui.set_loading(false);
                        }
                    });
                }
            }
        });
    }

    app.run()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn display_filename_uses_placeholder_when_empty_and_basename_when_set() {
        assert_eq!(
            display_filename("", "画像ファイルが未選択です"),
            "画像ファイルが未選択です"
        );
        assert_eq!(
            display_filename(r"C:\images\sample.png", "画像ファイルが未選択です"),
            "sample.png"
        );
    }

    #[test]
    fn parse_adjustment_input_handles_ascii_fullwidth_clamping_and_fallback() {
        assert_eq!(parse_adjustment_input("-45", 0, -90, 90), -45);
        assert_eq!(parse_adjustment_input("+30°", 0, -90, 90), 30);
        assert_eq!(parse_adjustment_input("－６５", 0, -100, 100), -65);
        assert_eq!(parse_adjustment_input("250", 0, -100, 100), 100);
        assert_eq!(parse_adjustment_input("-250", 0, -90, 90), -90);
        assert_eq!(parse_adjustment_input("", 25, -100, 100), 25);
        assert_eq!(parse_adjustment_input("-", -15, -100, 100), -15);
        assert_eq!(parse_adjustment_input("abc", 10, -100, 100), 10);
    }
}
